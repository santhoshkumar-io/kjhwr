#!/usr/bin/env python3
"""Phase 7 - print the three findings for the video, as Markdown on stdout.

AGENTS.md rule 2 says no number is ever typed by hand. This script is how that rule is
kept for `docs/findings.md`: the file is this script's output, redirected, so every
figure in it is reproducible and nothing in it was transcribed.

    uv run python backend/scripts/findings.py > docs/findings.md

Because the file IS the output, the numbers are formatted here the way they should read
in prose - thousands separators and all - rather than in the bare {:.0f} the diagnostic
scripts use. A reviewer checking the claim runs the command and diffs.

What this script deliberately does NOT do:

  * It does not recompute anything. Every number comes from the same
    `build_series` / `summarise` pair the API serves, so the findings and the screens
    cannot disagree.
  * It does not reach the network or the running server. It reads the committed CSVs,
    so it produces the same output on a laptop with no internet.
  * It does not choose its own date range. The findings describe the whole delivery
    range from decision 0002, which is what the brief asked about.

Phase 10 draws the video script from this file and is told to use no other numbers, so
anything the script needs has to appear here - hence the summary table at the end.
"""

from __future__ import annotations

import sys
from pathlib import Path

# backend/app is not an installed package. Running this as a script puts backend/scripts
# on sys.path, not backend/, so `app.*` would not resolve; pytest.ini and the Vercel
# entry point make it importable the same way, by putting backend/ on the path.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.data_loading import load_actuals, load_forecasts  # noqa: E402
from app.forecast_selection import DEADLINE_MODE, HOURS_AHEAD_MODE, build_series  # noqa: E402
from app.metrics import summarise  # noqa: E402

# Anchored to this file, so the working directory does not matter.
DATA_DIR = Path(__file__).resolve().parents[1] / "data"

# The lead times quoted in finding 2. Stops at 42 because coverage is complete to there
# and falls away above it - comparing 48 h against 0 h would compare different point sets.
LEAD_TIMES_HOURS = (0, 24, 42)


def mw(value: float) -> str:
    """A megawatt figure as it should read in prose."""
    return f"{value:,.0f} MW"


def signed_mw(value: float) -> str:
    """Bias carries its sign: +1,730 and -1,730 mean opposite things to a buyer.

    Zero is printed without one. After the correction the bias is zero by construction,
    and "+0 MW" reads as a tiny positive lean rather than as none at all.
    """
    if round(value) == 0:
        return "0 MW"
    return f"{value:+,.0f} MW"


def main() -> int:
    actuals = load_actuals(DATA_DIR / "actuals.csv")
    forecasts = load_forecasts(DATA_DIR / "forecasts.csv")

    deadline = summarise(build_series(actuals, forecasts, DEADLINE_MODE))
    raw = deadline["raw"]
    corrected = deadline["bias_corrected"]
    worst = deadline["worst_days"][0]

    by_lead = {
        hours: summarise(build_series(actuals, forecasts, HOURS_AHEAD_MODE, hours=hours))
        for hours in LEAD_TIMES_HOURS
    }
    earliest, latest = LEAD_TIMES_HOURS[0], LEAD_TIMES_HOURS[-1]
    lead_rise = by_lead[latest]["raw"]["mae"] - by_lead[earliest]["raw"]["mae"]

    matched = deadline["points_matched"]
    above = matched - deadline["forecast_below_actual"]

    first_day = str(actuals["target_time"].min().date())
    last_day = str(actuals["target_time"].max().date())

    print("# Findings")
    print()
    print(
        f"Three things the January 2026 data says about the day-ahead wind forecast, for a"
        f" team buying power one day before delivery."
    )
    print()
    print(
        f"Delivery days {first_day} to {last_day}: {deadline['points_requested']:,}"
        f" half-hours, of which {matched:,} had a forecast the buyer could have seen at the"
        f" 11:00 UTC deadline."
    )
    print()
    print(
        "Generated by `backend/scripts/findings.py`. Every number here is that script's"
        " output; none was typed by hand."
    )
    print()

    print("## 1. The forecast leans high, and most of that lean is not forecast error")
    print()
    print(
        f"Across January the forecast ran **{signed_mw(raw['bias'])} above** what the wind"
        f" actually delivered, on average. That lean is {raw['bias'] / raw['mae']:.0%} of the"
        f" {mw(raw['mae'])} typical miss, and the forecast came in high on"
        f" **{above / matched:.0%}** of matched half-hours."
    )
    print()
    print(
        "The reason matters more than the number. The two feeds measure different things:"
        " the forecast describes the wind generation that will be *available*, while the"
        " metered figure is what was actually *delivered*, after curtailment and balancing"
        " actions reduced it. In GB wind is curtailed regularly, so a forecast above actual"
        " is expected, and a large part of this gap was never a forecasting failure."
    )
    print()
    print(
        f"Remove that known lean and the typical miss falls from {mw(raw['mae'])} to"
        f" **{mw(corrected['mae'])}**, a reduction of"
        f" {1 - corrected['mae'] / raw['mae']:.0%}. That smaller number is the part that is"
        f" genuinely unpredictable."
    )
    print()
    print(
        f"**What a buyer does differently:** subtract roughly {mw(raw['bias'])} from the"
        f" headline forecast before deciding how much to buy, and size the safety margin"
        f" against the corrected error rather than the raw one. It is a lean, not a rule -"
        f" the forecast still fell below actual on"
        f" {deadline['forecast_below_actual'] / matched:.0%} of half-hours - so it cannot be"
        f" treated as a guaranteed one-way offset."
    )
    print()

    print("## 2. The earlier you must commit, the worse the forecast gets")
    print()
    print(
        "Measured by re-running the whole month at each setting, so the mix of delivery"
        " hours is identical every time:"
    )
    print()
    print("| Forecast made at least | Typical miss | Half-hours compared |")
    print("|---|---|---|")
    for hours in LEAD_TIMES_HOURS:
        point = by_lead[hours]
        print(
            f"| {hours} hours before delivery | {mw(point['raw']['mae'])} |"
            f" {point['points_matched']:,} |"
        )
    print()
    print(
        f"Committing {latest} hours ahead instead of at delivery time costs"
        f" **{mw(lead_rise)}** of accuracy, a"
        f" {by_lead[latest]['raw']['mae'] / by_lead[earliest]['raw']['mae'] - 1:.0%} increase"
        f" in the typical miss."
    )
    print()
    print(
        f"**What a buyer does differently:** treat the day-ahead deadline as a cost, not"
        f" just a constraint. Any flexibility that moves a decision later is worth up to"
        f" {mw(lead_rise)} of error per half-hour, which is the figure to weigh against"
        f" whatever that flexibility costs to buy."
    )
    print()

    print("## 3. Size cover on the bad half-hours, not the average one")
    print()
    print(
        f"The typical miss is {mw(raw['mae'])}, but nine times out of ten the miss was under"
        f" **{mw(raw['p90'])}** - {raw['p90'] / raw['mae']:.1f} times the average. Cover"
        f" built to the average is short in one half-hour out of every ten."
    )
    print()
    print(
        f"Whole days behave this way too. The worst delivery day, **{worst['day']}**, missed"
        f" by {mw(worst['mae'])} on average across its {worst['n']} half-hours - and its mean"
        f" bias was {signed_mw(worst['bias'])}, identical to the miss. Every single half-hour"
        f" that day was forecast too high. A bad day is not a mix of good and bad calls; it"
        f" is one wrong call repeated 48 times."
    )
    print()
    print(
        f"**What a buyer does differently:** hold cover against the {mw(raw['p90'])} figure"
        f" rather than the {mw(raw['mae'])} one, and expect the shortfall to arrive as whole"
        f" bad days rather than scattered bad half-hours - which is a position to plan"
        f" overnight, not something to fix half-hour by half-hour."
    )
    print()

    print("## The numbers behind these findings")
    print()
    print("Day-ahead deadline mode, whole delivery range.")
    print()
    print("| Measure | Raw | After removing the lean |")
    print("|---|---|---|")
    print(f"| Typical miss (MAE) | {mw(raw['mae'])} | {mw(corrected['mae'])} |")
    print(f"| With big misses weighted (RMSE) | {mw(raw['rmse'])} | {mw(corrected['rmse'])} |")
    print(f"| Average lean (mean bias) | {signed_mw(raw['bias'])} | {signed_mw(corrected['bias'])} |")
    print(f"| Miss beaten 9 times in 10 (P90) | {mw(raw['p90'])} | {mw(corrected['p90'])} |")
    print(f"| Half-hours measured | {raw['n']:,} | {corrected['n']:,} |")
    print()
    print(f"Lean removed: {signed_mw(corrected['bias_used'])}, measured over this same range.")
    print()
    print("Worst five delivery days, by typical miss:")
    print()
    print("| Day | Typical miss | Average lean | Half-hours |")
    print("|---|---|---|---|")
    for day in deadline["worst_days"]:
        print(f"| {day['day']} | {mw(day['mae'])} | {signed_mw(day['bias'])} | {day['n']} |")
    return 0


if __name__ == "__main__":
    sys.exit(main())
